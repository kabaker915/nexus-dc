import {
  VLAN, VLAN_NAMES, NTP_SERVER, SYSLOG_SERVER, MGMT_GATEWAY,
  describePort, hostName, mgmtIp, peerOf, portName, vendor, vendorKey, vlanForPeer,
} from './vendors.js';

function comwareInterface(app, dev, port, i, isHuawei) {
  const name = portName(port, i);
  const peer = peerOf(app, dev, port);
  const desc = describePort(app, dev, port);
  const out = [`interface ${name}`, ` description ${desc}`];
  if (!peer) {
    out.push(' shutdown');
    return out;
  }
  const vlan = vlanForPeer(peer);
  const trunk = peer.kind === 'switch48' || peer.kind === 'switch24' || peer.kind === 'router' || peer.kind === 'firewall';
  if (trunk) {
    out.push(' port link-type trunk');
    out.push(isHuawei ? ' port trunk allow-pass vlan 10 20 30 40 50' : ' port trunk permit vlan 10 20 30 40 50');
  } else if (vlan) {
    out.push(' port link-type access');
    out.push(` port default vlan ${vlan}`);
  }
  out.push(' undo shutdown');
  return out;
}

function iosInterface(app, dev, port, i) {
  const name = portName(port, i);
  const peer = peerOf(app, dev, port);
  const desc = describePort(app, dev, port);
  const out = [`interface ${name}`, ` description ${desc}`];
  if (!peer) {
    out.push(' shutdown');
    return out;
  }
  const vlan = vlanForPeer(peer);
  const trunk = peer.kind === 'switch48' || peer.kind === 'switch24' || peer.kind === 'router' || peer.kind === 'firewall';
  if (trunk) {
    out.push(' switchport mode trunk');
    out.push(' switchport trunk allowed vlan 10,20,30,40,50');
  } else if (vlan) {
    out.push(' switchport mode access');
    out.push(` switchport access vlan ${vlan}`);
  }
  out.push(' no shutdown');
  return out;
}

export function buildConfig(app, dev) {
  if (!dev) return '';
  const k = vendorKey(dev);
  const v = vendor(dev);
  const host = hostName(dev, app.state);
  const ip = mgmtIp(dev, app.state);
  const linked = dev.ports.filter((p) => p.cable && p.kind !== 'power');

  const vlans = new Set([VLAN.MGMT]);
  for (const p of dev.ports) {
    const peer = peerOf(app, dev, p);
    const vl = peer ? vlanForPeer(peer) : null;
    if (vl) vlans.add(vl);
  }

  if (v.family === 'linux') {
    const gw = MGMT_GATEWAY;
    return [
      `# ${host} — baseline generated by NEXUS NetDevOps`,
      `# vendor: ${v.full} · mgmt ${ip}/24 · gw ${gw}`,
      '',
      '# /etc/hostname',
      host.toLowerCase(),
      '',
      '# /etc/netplan/01-netcfg.yaml',
      'network:',
      '  version: 2',
      '  ethernets:',
      '    eth0:',
      `      addresses: [${ip}/24]`,
      `      gateway4: ${gw}`,
      '      nameservers:',
      '        addresses: [10.10.0.10, 223.5.5.5]',
      '      dhcp4: false',
      '      mtu: 1500',
      '',
      '# /etc/chrony/chrony.conf',
      `server ${NTP_SERVER} iburst`,
      'makestep 1.0 3',
      '',
      '# /etc/rsyslog.d/50-nexus.conf',
      `*.* @@${SYSLOG_SERVER}:514`,
      '',
      '# /etc/ssh/sshd_config.d/99-nexus.conf',
      'PermitRootLogin no',
      'PasswordAuthentication no',
      'MaxAuthTries 3',
      '',
      '# services',
      'systemctl enable --now node_exporter.service',
      'systemctl enable --now rsyslog.service',
      'systemctl enable --now chrony.service',
      '',
      `# interfaces: ${dev.ports.length} total, ${linked.length} cabled`,
    ].join('\n');
  }

  const isHuawei = k === 'huawei';
  const L = [];
  const sep = v.family === 'ios' ? '!' : '#';

  L.push(sep);
  L.push(` sysname ${host}`.trimStart());
  L.push(sep);

  if (v.family === 'comware') {
    L.push(` vlan batch ${[...vlans].sort((a, b) => a - b).join(' ')}`);
    L.push(sep);
    L.push(' stp global enable');
    L.push(' stp mode rstp');
    L.push(sep);
    L.push('interface Vlan-interface10');
    L.push(` ip address ${ip} 255.255.255.0`);
    L.push(` description MGMT`);
    L.push(sep);
    for (let i = 0; i < dev.ports.length; i++) {
      const p = dev.ports[i];
      if (p.kind === 'power') continue;
      for (const line of comwareInterface(app, dev, p, i, isHuawei)) L.push(line);
      L.push(sep);
    }
    if (dev.kind === 'router') {
      L.push('interface LoopBack0');
      L.push(` ip address 10.255.${ip.split('.')[2]}.${ip.split('.')[3]} 255.255.255.255`);
      L.push(sep);
      L.push(' ip route-static 0.0.0.0 0 10.0.0.254');
      L.push(' ospf 1 router-id ' + ip);
      L.push('  area 0.0.0.0');
      L.push('   network 10.0.0.0 0.0.0.255');
      L.push('   network 10.10.0.0 0.0.255.255');
      L.push(sep);
    }
    if (dev.kind === 'firewall') {
      L.push('security-zone name Trust');
      L.push(' import interface GigabitEthernet1/0/1');
      L.push('security-zone name Untrust');
      L.push(' import interface GigabitEthernet1/0/2');
      L.push('security-policy');
      L.push(' rule name allow-inside-out');
      L.push('  source-zone Trust');
      L.push('  destination-zone Untrust');
      L.push('  action permit');
      L.push(sep);
    }
    L.push('snmp-agent');
    L.push('snmp-agent sys-info version v2c v3');
    L.push('snmp-agent community read cipher %^%#NexusDc0ps%^%#');
    L.push('snmp-agent target-host trap address udp-domain 10.10.0.30 params securityname public v2c');
    L.push(`ntp-service unicast-server ${NTP_SERVER}`);
    L.push(`info-center loghost ${SYSLOG_SERVER}`);
    L.push('ssh server enable');
    L.push('local-user netops class manage');
    L.push(' password irreversible-cipher %^%#N3t0ps!2026%^%#');
    L.push(' service-type ssh');
    L.push(' authorization-role network-admin');
    L.push(sep);
    L.push('return');
    return L.join('\n');
  }

  // IOS style
  L.push(`hostname ${host}`);
  L.push(sep);
  for (const id of [...vlans].sort((a, b) => a - b)) {
    L.push(`vlan ${id}`);
    L.push(` name ${VLAN_NAMES[id] || `VLAN${id}`}`);
    L.push(sep);
  }
  L.push('interface Vlan10');
  L.push(' description MGMT');
  L.push(` ip address ${ip} 255.255.255.0`);
  L.push(' no shutdown');
  L.push(sep);
  for (let i = 0; i < dev.ports.length; i++) {
    const p = dev.ports[i];
    if (p.kind === 'power') continue;
    for (const line of iosInterface(app, dev, p, i)) L.push(line);
    L.push(sep);
  }
  if (dev.kind === 'router') {
    L.push('interface Loopback0');
    L.push(` ip address 10.255.${ip.split('.')[2]}.${ip.split('.')[3]} 255.255.255.255`);
    L.push(sep);
    L.push('ip route 0.0.0.0 0.0.0.0 10.0.0.254');
    L.push('router ospf 1');
    L.push(` router-id ${ip}`);
    L.push(' network 10.0.0.0 0.0.0.255 area 0');
    L.push(sep);
  }
  L.push('snmp-server community NexusDc0ps RO');
  L.push('snmp-server host 10.10.0.30 version 2c public');
  L.push(`ntp server ${NTP_SERVER}`);
  L.push(`logging host ${SYSLOG_SERVER}`);
  L.push('ip ssh version 2');
  L.push('username netops privilege 15 secret 9 $9$NexusDc0ps');
  L.push(sep);
  L.push('end');
  return L.join('\n');
}

/** Tiny LCS line diff — enough for config drift review. */
export function diffLines(oldText, newText) {
  const a = (oldText || '').split('\n');
  const b = (newText || '').split('\n');
  const n = a.length;
  const m = b.length;
  const dp = Array.from({ length: n + 1 }, () => new Uint16Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
    }
  }
  const out = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) { out.push({ t: ' ', text: a[i] }); i++; j++; }
    else if (dp[i + 1][j] >= dp[i][j + 1]) { out.push({ t: '-', text: a[i] }); i++; }
    else { out.push({ t: '+', text: b[j] }); j++; }
  }
  while (i < n) { out.push({ t: '-', text: a[i++] }); }
  while (j < m) { out.push({ t: '+', text: b[j++] }); }
  return out;
}
